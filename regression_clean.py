print("===== 清洗回归 =====")
for name, s in SAMPLES.items():
    out = clean_content(s)
    print(f"\n[{name}] 长度 {len(s)} -> {len(out)}")
    print(out)
    print("--- 断言 ---")
    bad = []
    for noise in ["Президент", "相关资讯", "继续阅读", "Image 2", "查看所有评论",
                  "©", "文章投诉热线", "选股器", "发布时间 2024", "更新时间 2024"]:
        if noise in out:
            bad.append(noise)
    print("  残留噪声:", bad if bad else "无(PASS)")

print("\n===== published_at 歧义处理 =====")
